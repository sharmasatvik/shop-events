package com.shop.order.domain;

import jakarta.persistence.*;

import java.time.Instant;
import java.util.UUID;

/**
 * Represent an order in the system. Currently, for practice the order only has
 * one SKU per order.
 */
@Entity
@Table(name = "orders")
public class Order {

    @Id
    private UUID id;

    /**
     * The unique identifier of the customer who placed the order.
     */
    private String customerId;

    /**
     * The quantity of the SKU ordered.
     */
    private int quantity;

    /**
     * The SKU identifier.
     */
    private String sku;

    /**
     * The current status of the order.
     */
    @Enumerated(EnumType.STRING)
    private OrderStatus status;

    /**
     * The time at which the order was created.
     */
    private Instant createdAt;

    /**
     * The time at which the order was updated.
     */
    private Instant updatedAt;

    protected Order() {
        // for JPA
    }

    public static Order newPending(final String customerId
            , final String sku
            , final int quantity) {
        var order = new Order();

        // Generated by us, so we know the id before saving (needed for the event)
        order.id = UUID.randomUUID();
        order.customerId = customerId;
        order.sku = sku;
        order.quantity = quantity;
        order.status = OrderStatus.PENDING;
        order.createdAt = Instant.now();
        order.updatedAt = order.createdAt;

        return order;
    }

    public UUID getId() {
        return id;
    }

    public String getCustomerId() {
        return customerId;
    }

    public String getSku() {
        return sku;
    }

    public int getQuantity() {
        return quantity;
    }

    public OrderStatus getStatus() {
        return status;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
