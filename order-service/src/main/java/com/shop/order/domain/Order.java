package com.shop.order.domain;

import jakarta.persistence.*;

import java.time.Instant;
import java.util.UUID;

/**
 * Represent an order in the system. Currently, for practice the order only has
 * one SKU per order.
 */
@Entity
@Table(name = "orders")
public class Order {

    @Id
    private UUID id;

    /**
     * The unique identifier of the customer who placed the order.
     */
    private String customerId;

    /**
     * The quantity of the SKU ordered.
     */
    private int quantity;

    /**
     * Reason for rejecting the order.
     */
    private String rejectReason;

    /**
     * The SKU identifier.
     */
    private String sku;

    /**
     * The current status of the order.
     */
    @Enumerated(EnumType.STRING)
    private OrderStatus status;

    /**
     * The time at which the order was created.
     */
    private Instant createdAt;

    /**
     * The time at which the order was updated.
     */
    private Instant updatedAt;

    protected Order() {
        // for JPA
    }

    /**
     * Creates a new order.
     *
     * @param customerId The customer for which the order is being created.
     * @param sku        The sku included in that order.
     * @param quantity   The quantity of the order.
     *
     * @return The order which has been created.
     */
    public static Order newPending(final String customerId
            , final String sku
            , final int quantity) {
        var order = new Order();

        // Generated by us, so we know the id before saving (needed for the event)
        order.id = UUID.randomUUID();
        order.customerId = customerId;
        order.sku = sku;
        order.quantity = quantity;
        order.status = OrderStatus.PENDING;
        order.createdAt = Instant.now();
        order.updatedAt = order.createdAt;

        return order;
    }

    /**
     * Confirms an order.
     */
    public void confirm() {
        requirePending();

        this.status = OrderStatus.CONFIRMED;
        this.updatedAt = Instant.now();
    }

    /**
     * Rejects an order with a reason.
     *
     * @param reason The reason for rejecting the order.
     */
    public void reject(final String reason) {
        requirePending();

        this.rejectReason = reason;
        this.status = OrderStatus.REJECTED;
        this.updatedAt = Instant.now();
    }

    /**
     * Checks whether the order is in pending state.
     */
    @Transient
    public boolean isPending() {
        return status == OrderStatus.PENDING;
    }

    /**
     * Enforces that the order being confirmed or rejected is in "Pending"
     * state.
     *
     * @throws IllegalStateException if the order is no longer pending
     */
    private void requirePending() {
        if (!isPending()) {
            throw new IllegalStateException("Order: " + id + " is already in: " + status + " status.");
        }
    }

    public UUID getId() {
        return id;
    }

    public String getCustomerId() {
        return customerId;
    }

    public String getSku() {
        return sku;
    }

    public int getQuantity() {
        return quantity;
    }

    public String getRejectReason() {
        return rejectReason;
    }

    public OrderStatus getStatus() {
        return status;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
